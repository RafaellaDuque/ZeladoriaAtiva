--  DDL - CRIACAO DAS 7 TABELAS DO DOMINIO (ORACLE SQL)

--  Tabela MUNICIPIO
CREATE TABLE MUNICIPIO (
    municipio_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR2(100) NOT NULL,
    uf CHAR(2) NOT NULL,
    codigo_ibge VARCHAR2(10),
    CONSTRAINT PK_MUNICIPIO PRIMARY KEY (municipio_id),
    CONSTRAINT UK_MUNICIPIO_IBGE UNIQUE (codigo_ibge),
    CONSTRAINT CHK_MUNICIPIO_UF CHECK (uf IN (
        'AC','AL','AP','AM','BA','CE','DF','ES','GO','MA','MT','MS','MG',
        'PA','PB','PR','PE','PI','RJ','RN','RS','RO','RR','SC','SP','SE','TO'
    ))
);

--  Tabela BAIRRO
CREATE TABLE BAIRRO (
    bairro_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR2(100) NOT NULL,
    regiao VARCHAR2(60) NOT NULL,
    populacao_estimada NUMBER(10) NOT NULL,
    indice_vulnerabilidade NUMBER(2) NOT NULL,
    municipio_id NUMBER(10) NOT NULL,
    CONSTRAINT PK_BAIRRO PRIMARY KEY (bairro_id),
    CONSTRAINT FK_BAIRRO_MUNICIPIO FOREIGN KEY (municipio_id) REFERENCES MUNICIPIO(municipio_id),
    CONSTRAINT CHK_BAIRRO_POPULACAO CHECK (populacao_estimada > 0),
    CONSTRAINT CHK_BAIRRO_VULNERABILIDADE CHECK (indice_vulnerabilidade BETWEEN 1 AND 5)
);

--  Tabela CIDADAO
CREATE TABLE CIDADAO (
    cidadao_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR2(100) NOT NULL,
    cpf VARCHAR2(14) NOT NULL,
    email VARCHAR2(100) NOT NULL,
    telefone VARCHAR2(20),
    data_cadastro DATE NOT NULL,
    CONSTRAINT PK_CIDADAO PRIMARY KEY (cidadao_id),
    CONSTRAINT UK_CIDADAO_CPF UNIQUE (cpf),
    CONSTRAINT UK_CIDADAO_EMAIL UNIQUE (email)
);

--  Tabela CHAMADO_ZELADORIA
CREATE TABLE CHAMADO_ZELADORIA (
    chamado_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    protocolo VARCHAR2(20) NOT NULL,
    titulo VARCHAR2(100) NOT NULL,
    descricao VARCHAR2(500) NOT NULL,
    categoria VARCHAR2(30) NOT NULL,
    logradouro VARCHAR2(150) NOT NULL,
    numero_endereco VARCHAR2(20),
    ponto_referencia VARCHAR2(150),
    url_foto VARCHAR2(255),
    status VARCHAR2(20) DEFAULT 'Aberto' NOT NULL,
    data_abertura DATE NOT NULL,
    total_votos NUMBER(10) DEFAULT 0 NOT NULL,
    cidadao_autor_id NUMBER(10) NOT NULL,
    bairro_id NUMBER(10) NOT NULL,
    CONSTRAINT PK_CHAMADO_ZELADORIA PRIMARY KEY (chamado_id),
    CONSTRAINT UK_CHAMADO_PROTOCOLO UNIQUE (protocolo),
    CONSTRAINT FK_CHAMADO_CIDADAO FOREIGN KEY (cidadao_autor_id) REFERENCES CIDADAO(cidadao_id),
    CONSTRAINT FK_CHAMADO_BAIRRO FOREIGN KEY (bairro_id) REFERENCES BAIRRO(bairro_id),
    CONSTRAINT CHK_CHAMADO_CATEGORIA CHECK (categoria IN ('Iluminacao', 'Asfalto', 'Limpeza', 'Drenagem')),
    CONSTRAINT CHK_CHAMADO_STATUS CHECK (status IN ('Aberto', 'Em_Andamento', 'Resolvido')),
    CONSTRAINT CHK_CHAMADO_VOTOS CHECK (total_votos >= 0)
);

--  Tabela VOTO_CHAMADO
CREATE TABLE VOTO_CHAMADO (
    voto_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    data_voto DATE NOT NULL,
    nivel_urgencia NUMBER(2) NOT NULL,
    comentario VARCHAR2(300),
    chamado_id NUMBER(10) NOT NULL,
    cidadao_id NUMBER(10) NOT NULL,
    CONSTRAINT PK_VOTO_CHAMADO PRIMARY KEY (voto_id),
    CONSTRAINT FK_VOTO_CHAMADO FOREIGN KEY (chamado_id) REFERENCES CHAMADO_ZELADORIA(chamado_id),
    CONSTRAINT FK_VOTO_CIDADAO FOREIGN KEY (cidadao_id) REFERENCES CIDADAO(cidadao_id),
    CONSTRAINT CHK_VOTO_URGENCIA CHECK (nivel_urgencia BETWEEN 1 AND 5),
    CONSTRAINT UK_VOTO_UNICO_POR_CIDADAO UNIQUE (chamado_id, cidadao_id)
);

--  Tabela ORGAO_RESPONSAVEL
CREATE TABLE ORGAO_RESPONSAVEL (
    orgao_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome_orgao VARCHAR2(120) NOT NULL,
    especialidade VARCHAR2(30) NOT NULL,
    telefone_contato VARCHAR2(20),
    email_ouvidoria VARCHAR2(100) NOT NULL,
    municipio_id NUMBER(10) NOT NULL,
    CONSTRAINT PK_ORGAO_RESPONSAVEL PRIMARY KEY (orgao_id),
    CONSTRAINT FK_ORGAO_MUNICIPIO FOREIGN KEY (municipio_id) REFERENCES MUNICIPIO(municipio_id),
    CONSTRAINT CHK_ORGAO_ESPECIALIDADE CHECK (especialidade IN ('Iluminacao', 'Asfalto', 'Limpeza', 'Drenagem'))
);

--  Tabela ORDEM_SERVICO
CREATE TABLE ORDEM_SERVICO (
    ordem_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    numero_os VARCHAR2(20) NOT NULL,
    status_execucao VARCHAR2(20) DEFAULT 'Pendente' NOT NULL,
    data_emissao DATE NOT NULL,
    data_conclusao DATE,
    parecer_tecnico VARCHAR2(400),
    url_foto_solucao VARCHAR2(255),
    chamado_id NUMBER(10) NOT NULL,
    orgao_id NUMBER(10) NOT NULL,
    CONSTRAINT PK_ORDEM_SERVICO PRIMARY KEY (ordem_id),
    CONSTRAINT UK_ORDEM_NUMERO_OS UNIQUE (numero_os),
    CONSTRAINT UK_ORDEM_CHAMADO_UNICO UNIQUE (chamado_id),
    CONSTRAINT FK_ORDEM_CHAMADO FOREIGN KEY (chamado_id) REFERENCES CHAMADO_ZELADORIA(chamado_id),
    CONSTRAINT FK_ORDEM_ORGAO FOREIGN KEY (orgao_id) REFERENCES ORGAO_RESPONSAVEL(orgao_id),
    CONSTRAINT CHK_ORDEM_STATUS CHECK (status_execucao IN ('Pendente', 'Equipe_Em_Campo', 'Concluida', 'Cancelada'))
);

