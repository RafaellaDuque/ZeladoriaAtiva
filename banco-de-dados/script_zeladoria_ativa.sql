--  DQL - CONSULTAS SQL QUE RESPONDEM PERGUNTAS REAIS DO DOMINIO


-- PERGUNTA 1: Qual e a fila de prioridade comunitaria atual para as subprefeituras
-- (chamados nao resolvidos ordenados por votos, urgencia media e vulnerabilidade)?
SELECT
    c.protocolo,
    c.titulo,
    c.categoria,
    c.status,
    b.nome AS bairro,
    m.nome AS municipio,
    m.uf,
    b.indice_vulnerabilidade,
    c.total_votos,
    ROUND(AVG(v.nivel_urgencia), 2) AS media_urgencia_comunidade,
    (c.total_votos * 10 + b.indice_vulnerabilidade * 5) AS score_prioridade
FROM CHAMADO_ZELADORIA c
INNER JOIN BAIRRO b ON c.bairro_id = b.bairro_id
INNER JOIN MUNICIPIO m ON b.municipio_id = m.municipio_id
LEFT JOIN VOTO_CHAMADO v ON c.chamado_id = v.chamado_id
WHERE c.status IN ('Aberto', 'Em_Andamento')
GROUP BY
    c.chamado_id, c.protocolo, c.titulo, c.categoria, c.status,
    b.nome, m.nome, m.uf, b.indice_vulnerabilidade, c.total_votos
ORDER BY
    score_prioridade DESC,
    media_urgencia_comunidade DESC;

-- PERGUNTA 2: Quais bairros concentram maior volume de chamados e engajamento cidadao?
SELECT
    m.nome AS municipio,
    m.uf,
    b.nome AS bairro,
    b.regiao,
    b.indice_vulnerabilidade,
    COUNT(DISTINCT c.chamado_id) AS total_chamados_bairro,
    NVL(SUM(c.total_votos), 0) AS soma_votos_regiao
FROM BAIRRO b
INNER JOIN MUNICIPIO m ON b.municipio_id = m.municipio_id
LEFT JOIN CHAMADO_ZELADORIA c ON b.bairro_id = c.bairro_id
GROUP BY
    m.nome, m.uf, b.bairro_id, b.nome, b.regiao, b.indice_vulnerabilidade
ORDER BY
    soma_votos_regiao DESC;

-- PERGUNTA 3: Qual o status de acompanhamento e tempo de resolucao (em dias) das Ordens de Servico?
SELECT
    os.numero_os,
    os.status_execucao,
    c.protocolo AS protocolo_chamado,
    c.titulo AS problema_reportado,
    b.nome AS bairro,
    o.nome_orgao AS orgao_responsavel,
    c.data_abertura AS abertura_chamado,
    os.data_emissao AS emissao_os,
    os.data_conclusao AS conclusao_os,
    (os.data_conclusao - c.data_abertura) AS dias_ate_resolucao,
    os.parecer_tecnico
FROM ORDEM_SERVICO os
INNER JOIN CHAMADO_ZELADORIA c ON os.chamado_id = c.chamado_id
INNER JOIN BAIRRO b ON c.bairro_id = b.bairro_id
INNER JOIN ORGAO_RESPONSAVEL o ON os.orgao_id = o.orgao_id
ORDER BY
    os.data_emissao DESC;
